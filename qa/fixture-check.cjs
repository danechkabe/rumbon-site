const {chromium}=require('/Users/mac/Downloads/jcode-lite-macos-x64-latest/preset/mcp/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true,executablePath:'/Users/mac/Library/Caches/ms-playwright/chromium-1217/chrome-mac-x64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4174/',{waitUntil:'networkidle'});
assert.equal(await page.locator('.room-card').count(),2);
assert.equal(await page.locator('.price-marker').count(),1);
await page.locator('.price-marker').click();
await page.locator('.popup-room').waitFor();
assert.match(await page.locator('.popup-room').innerText(),/Room 1 of 3/);
await page.getByRole('button',{name:'Next',exact:true}).click();
assert.match(await page.locator('.popup-room').innerText(),/Room 2 of 3/);
await page.getByRole('button',{name:'Next',exact:true}).click();
assert.match(await page.locator('.popup-room').innerText(),/Room 1 of 3/);
await page.locator('.popup-room a').click();
assert.match(page.url(),/rooms\/roma-areeiro-600\/$/);
await page.locator('[data-gallery-index="0"]').click();
assert.equal(await page.locator('#gallery-dialog').evaluate(el=>el.open),true);
await page.locator('[data-gallery-next]').click();
assert.equal(await page.locator('#gallery-counter').innerText(),'2 / 2');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#gallery-dialog').evaluate(el=>el.open),false);
await page.locator('.detail-section .button').click();
assert.match(page.url(),/apartments\/qa-apartment\/$/);
assert.equal(await page.locator('.room-card').count(),3);
assert.match(await page.locator('.inline-status').innerText(),/2 of 3 rooms available/);
const grayscale=await page.locator('.room-card.occupied img').evaluate(el=>getComputedStyle(el).filter);
assert.equal(grayscale,'grayscale(1)');
assert.equal(await page.getByText('Ask about the whole apartment',{exact:true}).count(),0);
await page.setViewportSize({width:375,height:812});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'qa/screenshots/apartment-fixture-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('PASS: apartment-only room list, occupied grayscale/counts, map marker grouping, carousel wrap, gallery, apartment navigation, mobile overflow.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
